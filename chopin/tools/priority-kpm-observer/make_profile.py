#!/usr/bin/env python3
"""Generate selective runtime identity anchors from the exact accepted artifact.

This does not prove a running Image hash. The controller additionally requires
the parent's independent readback/boot-id record. No alternative profile flag.
"""
import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

if sys.flags.optimize:
    raise RuntimeError("Assertions must be enabled; refusing an optimized Python run")

IMAGE_SHA = "6702e417fc0f731923be2f35e55ba96ffe0644e1a67275d7e5ebd09e91a865f1"
IMAGE_SIZE = 35646848
KPIMG_SHA = "554aa43ff1594ea516eb9d74581565aea07e29665ffaf702a3c87d556a7a2425"
SOURCE = "16c713d934ab7cfed5c4798497c48bab7e9db025"
SLOTS = [
    ("priority_uid_filter_bitmap", 8),
    ("susfs_priority_app_strings", 8),
    ("susfs_priority_app_strings_running", 4),
    ("susfs_set_priority_uid_filter.is_uid_filter_set_before", 1),
]
ANCHORS = [
    "susfs_set_priority_uid_filter", "susfs_priority_app_strings_worker",
    "susfs_is_priority_uid_filtered", "ksu_track_throne_tw_func",
    "sukisu_kpm_bridge", "SyS_getpriority",
]
SYMBOL_ONLY = ["ksu_kpm_bridge_trampoline"]  # paired hook changes its entry bytes
BOUNDS = ["_text", "__bss_start", "__bss_stop", "_end"]
PROOF_ONLY = ["__init_begin", "__init_end", "__alt_instructions", "__alt_instructions_end"]


def digest(b):
    return hashlib.sha256(b).hexdigest()


def make(image, map_bytes, kpimg):
    assert len(image) == IMAGE_SIZE and digest(image) == IMAGE_SHA, "wrong raw Image"
    assert digest(kpimg) == KPIMG_SHA, "wrong paired kpimg"
    names = BOUNDS + [n for n, _ in SLOTS] + ANCHORS + SYMBOL_ONLY
    found = {n: [] for n in names+PROOF_ONLY}
    for line in map_bytes.decode("utf-8").splitlines():
        a = line.split()
        if len(a) == 3 and a[2] in found:
            found[a[2]].append((int(a[0], 16), a[1]))
    assert all(len(v) == 1 for v in found.values()), "missing/duplicate exact symbol"
    base = found["_text"][0][0]
    bs, be, end = (found[n][0][0] for n in BOUNDS[1:])
    assert base < bs < be <= end and base >> 48 == 0xFFFF
    symbols = []
    for n in names:
        addr, typ = found[n][0]
        symbols.append({"name": n, "offset": addr-base, "type": typ})
    for n, width in SLOTS:
        addr, typ = found[n][0]
        assert typ in "bB" and bs <= addr and addr+width <= be
        assert addr % width == 0
    anchors = []
    init_start, init_end = (found[n][0][0] for n in PROOF_ONLY[:2])
    for n in ANCHORS:
        addr, typ = found[n][0]
        off = addr-base
        assert typ in "tT" and addr % 4 == 0 and off+32 <= len(image) and addr+32 < bs
        assert addr+32 <= init_start or init_end <= addr, "anchor is in freed init memory"
        anchors.append({"name": n, "offset": off, "bytes_hex": image[off:off+32].hex()})
    # ARM64 4.14 alt_instr: relative s32 orig/alt offsets, u16 capability,
    # u8 original/replacement lengths. Reject a CPU alternative touching anchors.
    alt_start, alt_end = (found[n][0][0] for n in PROOF_ONLY[2:])
    assert base <= alt_start < alt_end <= base+len(image) and (alt_end-alt_start) % 12 == 0
    for record in range(alt_start, alt_end, 12):
        orig, _, _, orig_len, alt_len = struct.unpack_from("<iiHBB", image, record-base)
        assert orig_len % 4 == alt_len % 4 == 0
        target = record+orig
        for anchor in anchors:
            start = base+anchor["offset"]
            assert not (target < start+32 and start < target+orig_len), "anchor is patched by CPU alternatives"
    profile = {"schema": 1, "profile": "r18-legacy-ci41100-readonly",
               "source_commit": SOURCE, "image_sha256": IMAGE_SHA,
               "image_size": IMAGE_SIZE, "system_map_sha256": digest(map_bytes),
               "paired_kpimg_sha256": KPIMG_SHA,
               "pinned_kp_headers_commit": "a3965c6e137e46b2c94a69eeb5a7e4696a3abbb0",
               "identity_scope": "exact file binding plus selective runtime anchors; not runtime full-image hashing",
               "protocol_base": "0x50520100", "symbols": symbols,
               "runtime_anchor_review": {
                   "all_outside_init_memory": True,
                   "arm64_alternative_records_checked": (alt_end-alt_start)//12,
                   "alternative_overlap": [],
                   "known_runtime_hook_excluded_from_byte_fingerprints": SYMBOL_ONLY},
               "slots": [{"name": n, "width": w} for n, w in SLOTS], "anchors": anchors}
    h = ["/* Generated by make_profile.py from the exact artifact. Do not edit. */",
         "#ifndef CHOPIN_PRIORITY_PROFILE_H", "#define CHOPIN_PRIORITY_PROFILE_H",
         '#define OBS_IMAGE_SHA "'+IMAGE_SHA+'"',
         '#define OBS_KPIMG_SHA "'+KPIMG_SHA+'"',
         '#define OBS_INIT_ARGS "raw-sha256='+IMAGE_SHA+'"',
         '#define OBS_NAME "chopin-priority-ro-r18"',
         "#define OBS_PROTOCOL_BASE 0x50520100UL", "#define OBS_SYMBOL_COUNT 15",
         "#define OBS_SLOT_FIRST 4", "#define OBS_SLOT_COUNT 4",
         "#define OBS_ANCHOR_FIRST 8", "#define OBS_ANCHOR_COUNT 6",
         "struct obs_symbol { const char *name; unsigned long offset; };",
         "static const struct obs_symbol obs_symbols[OBS_SYMBOL_COUNT] = {"]
    h += ['    {"%s", 0x%xUL},' % (x["name"], x["offset"]) for x in symbols]
    h += ["};", "static const unsigned char obs_widths[OBS_SLOT_COUNT] = {8, 8, 4, 1};",
          "static const unsigned char obs_anchors[OBS_ANCHOR_COUNT][32] = {"]
    h += ["    {"+", ".join("0x"+x["bytes_hex"][i:i+2] for i in range(0,64,2))+"}," for x in anchors]
    h += ["};", "#endif", ""]
    header = "\n".join(h).encode()
    profile["generated_header_sha256"] = digest(header)
    return header, (json.dumps(profile, indent=2, ensure_ascii=False)+"\n").encode()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--image", type=Path, required=True)
    ap.add_argument("--system-map", type=Path, required=True)
    ap.add_argument("--kpimg", type=Path, required=True)
    ap.add_argument("--output-dir", type=Path, required=True)
    a = ap.parse_args()
    h, j = make(a.image.read_bytes(), a.system_map.read_bytes(), a.kpimg.read_bytes())
    a.output_dir.mkdir(parents=True, exist_ok=True)
    (a.output_dir/"profile.h").write_bytes(h)
    (a.output_dir/"profile.json").write_bytes(j)


if __name__ == "__main__":
    main()
